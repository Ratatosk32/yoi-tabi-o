"""Subset the self-hosted fonts for the Japan Trip PWA.

Run (from anywhere):
    design/tools/.venv/Scripts/python design/tools/subset-fonts.py

Reads (read-only) every text file of the app + PLAN.md + the mockup, collects the
Japanese characters actually used, and writes:
    design/fonts/shippori-mincho-500.kana.woff2   kana + JP punctuation + digits
    design/fonts/shippori-mincho-500.kanji.woff2  only the kanji the app uses
    design/fonts/lora-var.woff2                   Latin + macrons + Cyrillic, wght 400..700
    design/fonts/fonts.css                        @font-face rules with unicode-range
Re-run after the phrase data changes: a kanji missing from the subset is not an
error, it simply falls back to the system Mincho (see DESIGN.md, "Шрифты").
"""
import io, sys, pathlib
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[2]
DESIGN = ROOT / "design"
SRC = DESIGN / "fonts" / "src"
OUT = DESIGN / "fonts"

def corpus():
    files = [ROOT / "PLAN.md", DESIGN / "mockup.html"]
    app = ROOT / "app"
    for ext in ("*.json", "*.js", "*.html", "*.webmanifest"):
        files += [p for p in app.rglob(ext) if "vendor" not in p.parts]
    text = ""
    for p in files:
        if p.exists():
            text += io.open(p, encoding="utf-8", errors="ignore").read()
    return text

def is_kanji(c):
    o = ord(c)
    return 0x4E00 <= o <= 0x9FFF or 0x3400 <= o <= 0x4DBF or c in "々〆"

def ranges(cps):
    cps = sorted(set(cps)); out = []; i = 0
    while i < len(cps):
        j = i
        while j + 1 < len(cps) and cps[j + 1] == cps[j] + 1:
            j += 1
        out.append(f"U+{cps[i]:04X}" if i == j else f"U+{cps[i]:04X}-{cps[j]:04X}")
        i = j + 1
    return ", ".join(out)

def make(src, dst, unicodes, keep_var=False):
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["kern", "liga", "locl", "palt", "vert", "vrt2", "ccmp", "mark", "mkmk"]
    opts.name_IDs = [1, 2, 3, 4, 6, 13, 14]   # keep the licence strings
    opts.notdef_outline = True
    opts.desubroutinize = True
    font = TTFont(src)
    have = set(font.getBestCmap().keys())
    want = sorted(set(unicodes) & have)
    s = subset.Subsetter(opts); s.populate(unicodes=want); s.subset(font)
    font.flavor = "woff2"; font.save(dst)
    return want, pathlib.Path(dst).stat().st_size

text = corpus()
kanji = sorted({ord(c) for c in text if is_kanji(c)})
# numerals & units numbers.js can generate even if not literally present
kanji = sorted(set(kanji) | {ord(c) for c in "〇一二三四五六七八九十百千万円時分半秒年月日曜火水木金土午前後今明昨毎週間旅"})
kana = list(range(0x3041, 0x3097)) + list(range(0x3099, 0x3100)) \
     + list(range(0x3000, 0x3004)) + list(range(0x3008, 0x3012)) + [0x3014, 0x3015, 0x301C, 0x25CB, 0x00D7, 0x2026, 0x2015] \
     + list(range(0xFF01, 0xFF5F)) + list(range(0x30, 0x3A)) + [0xFFE5, 0x00A5]

mincho = SRC / "shipporimincho-ShipporiMincho-Medium.ttf"
k1, s1 = make(mincho, OUT / "shippori-mincho-500.kana.woff2", kana)
k2, s2 = make(mincho, OUT / "shippori-mincho-500.kanji.woff2", kanji)

latin = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) \
      + [0x100, 0x101, 0x112, 0x113, 0x12A, 0x12B, 0x14C, 0x14D, 0x16A, 0x16B] \
      + list(range(0x2010, 0x2027)) + [0x2030, 0x2032, 0x2033, 0x2039, 0x203A, 0x20AC, 0x20BD, 0x2116, 0x2190, 0x2192, 0x2212, 0x00D7]
cyr = list(range(0x400, 0x460)) + [0x490, 0x491]
k3, s3 = make(SRC / "lora-Lora[wght].ttf", OUT / "lora-var.woff2", latin + cyr)

css = f"""/* GENERATED by design/tools/subset-fonts.py - do not edit by hand.
 * Shippori Mincho (c) FONTDASU, Lora (c) Cyreal - SIL OFL 1.1, see fonts/LICENSE-*.txt
 * Sizes: kana {s1/1024:.0f} KB, kanji {s2/1024:.0f} KB ({len(k2)} kanji), lora {s3/1024:.0f} KB. */
@font-face {{
  font-family: "Shippori Mincho"; font-style: normal; font-weight: 500; font-display: swap;
  src: url("shippori-mincho-500.kana.woff2") format("woff2");
  unicode-range: {ranges(k1)};
}}
@font-face {{
  font-family: "Shippori Mincho"; font-style: normal; font-weight: 500; font-display: swap;
  src: url("shippori-mincho-500.kanji.woff2") format("woff2");
  unicode-range: {ranges(k2)};
}}
@font-face {{
  font-family: "Lora"; font-style: normal; font-weight: 400 700; font-display: swap;
  src: url("lora-var.woff2") format("woff2");
  unicode-range: {ranges(k3)};
}}
"""
io.open(OUT / "fonts.css", "w", encoding="utf-8", newline="\n").write(css)
missing = [chr(c) for c in kanji if c not in set(k2)]
sys.stdout.reconfigure(encoding="utf-8")
print(f"kana  {len(k1)} glyphs {s1/1024:.1f} KB")
print(f"kanji {len(k2)} glyphs {s2/1024:.1f} KB; not in font: {''.join(missing) or '-'}")
print(f"lora  {len(k3)} glyphs {s3/1024:.1f} KB")
