// Ship the dictionary into the app: dictionary/out/dict-{core,rest}.json → app/data/dict-{core,rest}.json,
// dictionary/tools/dict-search.mjs → app/modules/dict-search.js (a verbatim copy with a header).
// The source of truth stays in dictionary/ (built from JMdict by dictionary/tools/build-dict.mjs).
// Run: node tools/build-dict-app.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'dictionary');
const APP = join(ROOT, 'app');
export const DICT_FORMAT = 'japan-trip-dict/1';

/** Checks the pair and returns { core, rest, dictDate }. Throws on any inconsistency. */
export function checkPair(core, rest) {
  const fail = (m) => { throw new Error('dictionary: ' + m); };
  for (const [name, d] of [['core', core], ['rest', rest]]) {
    if (d.format !== DICT_FORMAT) fail(`${name}: format ${d.format}`);
    if (d.part !== name) fail(`${name}: part ${d.part}`);
    if (!Array.isArray(d.fields) || !Array.isArray(d.rows)) fail(`${name}: fields/rows missing`);
    if (d.rows.length !== d.count) fail(`${name}: count ${d.count} ≠ ${d.rows.length} rows`);
    if (!/CC BY-SA 4\.0/.test(d.license || '') || !/edrdg\.org/.test(d.attribution || '')) fail(`${name}: licence / attribution missing`);
  }
  if (JSON.stringify(core.fields) !== JSON.stringify(rest.fields)) fail('fields differ between core and rest');
  if (core.count + rest.count !== core.total || core.total !== rest.total) fail('core + rest ≠ total');
  const dictDate = (core.source.match(/dictDate (\d{4}-\d{2}-\d{2})/) || [])[1];
  if (!dictDate) fail('no dictDate in source');
  return { core, rest, dictDate };
}

export function buildDictApp() {
  const core = JSON.parse(readFileSync(join(SRC, 'out', 'dict-core.json'), 'utf8'));
  const rest = JSON.parse(readFileSync(join(SRC, 'out', 'dict-rest.json'), 'utf8'));
  const { dictDate } = checkPair(core, rest);
  // copy the files byte for byte (they are already minified)
  writeFileSync(join(APP, 'data', 'dict-core.json'), readFileSync(join(SRC, 'out', 'dict-core.json')));
  writeFileSync(join(APP, 'data', 'dict-rest.json'), readFileSync(join(SRC, 'out', 'dict-rest.json')));
  const search = readFileSync(join(SRC, 'tools', 'dict-search.mjs'), 'utf8');
  writeFileSync(join(APP, 'modules', 'dict-search.js'),
    '// GENERATED by tools/build-dict-app.mjs from dictionary/tools/dict-search.mjs. Do not edit here.\n' + search);
  return { total: core.total, core: core.count, rest: rest.count, dictDate };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const r = buildDictApp();
  console.log(`dictionary: ${r.core} core + ${r.rest} rest = ${r.total} entries, dictDate ${r.dictDate} → app/data/dict-*.json, app/modules/dict-search.js`);
}
