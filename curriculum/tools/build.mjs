// Builds the curriculum corpus: curriculum/src/*.mjs + app/data/phrases.json (read-only)
//   -> curriculum/data/curriculum.json, curriculum/SUMMARY.md
// Run: node curriculum/tools/build.mjs   (then node curriculum/tools/validate.mjs)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { rubyToJa, rubyToKana } from './lib.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const cur = join(here, '..');
const root = join(cur, '..');
const imp = (p) => import(pathToFileURL(join(cur, 'src', p)).href);

const { UNITS, CATEGORIES } = await imp('units.mjs');
const { EN } = await imp('existing-en.mjs');
const LESSON_FILES = ['u01-u04.mjs', 'u05-u07.mjs', 'u08-u10.mjs', 'u11-u14.mjs'];
const lessons = [];
for (const f of LESSON_FILES) {
  try { lessons.push(...(await imp(f)).LESSONS); }
  catch (e) { if (e.code !== 'ERR_MODULE_NOT_FOUND') throw e; console.warn('missing source file', f); }
}

const src = JSON.parse(readFileSync(join(root, 'app', 'data', 'phrases.json'), 'utf8'));
const old = new Map(src.items.map((it) => [it.id, it]));

const PREFIX_CAT = { taxi: 'transport', card: 'cards' };
function catOf(id, kind) {
  const parts = id.split('.');
  const seg = parts[0] === 'hear' ? parts[1] : parts[0];
  return PREFIX_CAT[seg] || seg;
}

const items = [];
const unitById = Object.fromEntries(UNITS.map((u) => [u.id, u]));
let order = 0;
const lessonMeta = [];
for (const L of lessons) {
  const unit = unitById[L.code.slice(0, 3)];
  const ids = [];
  for (const entry of L.items) {
    let it;
    if (typeof entry === 'string') {
      const o = old.get(entry);
      if (!o) throw new Error(`${L.code}: unknown v1 id ${entry}`);
      const en = EN[entry];
      if (!en) throw new Error(`no EN translation for ${entry}`);
      it = { id: o.id, cat: o.cat, kind: o.kind, en: en[0], ja: o.ja, ruby: o.ruby, kana: o.kana, romaji: o.romaji };
      if (o.tts) it.tts = o.tts;
      if (en[1]) it.note = en[1];
      if (o.pattern) it.pattern = o.pattern;
      if (o.replyTo) it.replyTo = [...o.replyTo];
      if (o.replies) it.replies = [...o.replies];
      it.src = 'v1';
    } else {
      const [id, kind, ruby, romaji, en, note, extra = {}] = entry;
      it = { id, cat: extra.cat || catOf(id, kind), kind, en, ja: rubyToJa(ruby), ruby, kana: rubyToKana(ruby), romaji };
      if (extra.tts) it.tts = extra.tts;
      if (note) it.note = note;
      if (extra.pattern) it.pattern = extra.pattern;
      if (extra.replies) it.replies = [...extra.replies];
      if (extra.replyTo) it.replyTo = [...extra.replyTo];
      if (extra.tags) it.extraTags = extra.tags;
      it.src = 'new';
    }
    it.lesson = L.code;
    it.level = L.level;
    it.order = ++order;
    it.tags = [unit.path, ...(it.extraTags || [])];
    delete it.extraTags;
    items.push(it);
    ids.push(it.id);
  }
  lessonMeta.push({ code: L.code, unit: unit.id, title: L.title, goal: L.goal, level: L.level, path: unit.path, patterns: L.patterns || [], count: ids.length, ids });
}

// Symmetric links: replies on hear items <-> replyTo on say/pattern items.
const byId = new Map(items.map((it) => [it.id, it]));
for (const it of items) {
  for (const r of it.replies || []) {
    const t = byId.get(r);
    if (t) { t.replyTo = t.replyTo || []; if (!t.replyTo.includes(it.id)) t.replyTo.push(it.id); }
  }
  for (const r of it.replyTo || []) {
    const t = byId.get(r);
    if (t) { t.replies = t.replies || []; if (!t.replies.includes(it.id)) t.replies.push(it.id); }
  }
}
// Field order
const out = items.map((it) => {
  const o = { id: it.id, cat: it.cat, kind: it.kind, en: it.en, ja: it.ja, ruby: it.ruby, kana: it.kana, romaji: it.romaji };
  for (const k of ['tts', 'note', 'pattern', 'replyTo', 'replies']) if (it[k] && (!Array.isArray(it[k]) || it[k].length)) o[k] = it[k];
  Object.assign(o, { tags: it.tags, lesson: it.lesson, level: it.level, order: it.order, src: it.src });
  return o;
});

mkdirSync(join(cur, 'data'), { recursive: true });
const data = { version: 1, generated: new Date().toISOString().slice(0, 10), categories: CATEGORIES, units: UNITS, lessons: lessonMeta, items: out };
writeFileSync(join(cur, 'data', 'curriculum.json'), JSON.stringify(data, null, 1) + '\n', 'utf8');

// ---------- SUMMARY.md ----------
const cnt = (arr, key) => arr.reduce((a, x) => ((a[key(x)] = (a[key(x)] || 0) + 1), a), {});
const kinds = ['say', 'hear', 'pattern', 'card'];
let md = `# Curriculum summary\n\nGenerated by \`curriculum/tools/build.mjs\` (${data.generated}). Total items: **${out.length}** (v1 reused: ${out.filter((x) => x.src === 'v1').length}, new: ${out.filter((x) => x.src === 'new').length}); lessons: **${lessonMeta.length}**.\n\n`;
md += '## By unit\n\n| Unit | Path | Lessons | Items | say | hear | pattern | card | words |\n|---|---|---|---|---|---|---|---|---|\n';
for (const u of UNITS) {
  const its = out.filter((x) => x.lesson.startsWith(u.id));
  const k = cnt(its, (x) => x.kind);
  md += `| ${u.id} ${u.title} | ${u.path} | ${lessonMeta.filter((l) => l.unit === u.id).length} | ${its.length} | ${kinds.map((x) => k[x] || 0).join(' | ')} | ${its.filter((x) => x.tags.includes('word')).length} |\n`;
}
md += '\n## By level\n\n| Level | Items | say | hear | pattern | card |\n|---|---|---|---|---|---|\n';
for (const lv of [1, 2, 3, 4, 5]) {
  const its = out.filter((x) => x.level === lv); const k = cnt(its, (x) => x.kind);
  md += `| ${lv} | ${its.length} | ${kinds.map((x) => k[x] || 0).join(' | ')} |\n`;
}
md += '\n## By path\n\n| Path | Lessons | Items |\n|---|---|---|\n';
for (const p of ['core', 'ext', 'ref']) md += `| ${p} | ${lessonMeta.filter((l) => l.path === p).length} | ${out.filter((x) => x.tags[0] === p).length} |\n`;
md += '\n## Lessons\n\n| Lesson | Level | Title | Items | say/hear/pattern/card | New patterns |\n|---|---|---|---|---|---|\n';
for (const l of lessonMeta) {
  const its = l.ids.map((id) => byId.get(id)); const k = cnt(its, (x) => x.kind);
  md += `| ${l.code} | ${l.level} | ${l.title} | ${l.count} | ${kinds.map((x) => k[x] || 0).join('/')} | ${l.patterns.join(', ')} |\n`;
}
writeFileSync(join(cur, 'SUMMARY.md'), md, 'utf8');
console.log(`items ${out.length} (v1 ${out.filter((x) => x.src === 'v1').length}, new ${out.filter((x) => x.src === 'new').length}), lessons ${lessonMeta.length}`);
